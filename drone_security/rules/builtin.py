"""Predefined security and flight-safety rules.

First draft generated by Claude Code from the feature spec ("alert on people at
the perimeter at night, loitering, repeat vehicles, drone safety"); thresholds,
severities and the whitelist handling were then reviewed and adjusted by hand.
All thresholds live in config/property.json.
"""
from __future__ import annotations

from typing import Iterable

from ..models import Alert, Severity
from ..perception.lexicon import SUSPICIOUS_ACTIONS, SUSPICIOUS_ATTRIBUTES
from .engine import Rule, RuleContext


def _verb(action: str | None) -> str:
    return {
        "climbing": "climbing", "tampering": "tampering with access point", "peering": "peering into property",
        "loitering": "loitering", "standing": "standing", "entering": "entering", "exiting": "leaving",
        "parked": "parked", "walking": "walking", "running": "running",
    }.get(action or "", "detected")


# --------------------------------------------------------------------- security rules
class SuspiciousActivityRule(Rule):
    rule_id = "R-SUSPICIOUS"
    title = "Suspicious behaviour (climbing, tampering, masked, break-in tools)"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        for det, upd in ctx.observations:
            if det.category != "person":
                continue
            flags = [a for a in det.attributes if a in SUSPICIOUS_ATTRIBUTES]
            if det.action not in SUSPICIOUS_ACTIONS and not flags:
                continue
            severe = det.action in {"climbing", "tampering"} or (flags and ctx.is_night)
            who = det.display_name
            extra = f" with {', '.join(f for f in flags if f != 'masked')}" if any(f != "masked" for f in flags) else ""
            yield self.alert(
                ctx, Severity.CRITICAL if severe else Severity.HIGH,
                f"{who} {_verb(det.action)}{extra} at {ctx.zone_name(det.zone)}, {ctx.hhmm}.",
                zone=det.zone, entity_id=det.entity_id,
                dedupe_key=f"{self.rule_id}|{det.entity_id}|{det.action}",  # climbing -> tampering is an escalation
                action="Possible intrusion in progress: notify on-call guard and police, keep drone on target, record continuously.",
            )


class LoiteringRule(Rule):
    """Fires immediately when the caption itself describes loitering."""

    rule_id = "R-LOITER"
    title = "Person loitering"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        for det, upd in ctx.observations:
            if det.category == "person" and det.action == "loitering":
                yield self.alert(
                    ctx, Severity.HIGH if ctx.is_night else Severity.MEDIUM,
                    f"{det.display_name} loitering at {ctx.zone_name(det.zone)}, {ctx.hhmm}.",
                    zone=det.zone, entity_id=det.entity_id,
                    action="Hover and keep the person in frame; play deterrent announcement if they stay.",
                )


class DwellTimeRule(Rule):
    """Fires when the tracker observes the same person in one zone for longer than the loiter threshold."""

    rule_id = "R-DWELL"
    title = "Prolonged presence in one zone"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        limit = ctx.config.thresholds.loiter_minutes * 60
        for det, upd in ctx.observations:
            if det.category != "person" or upd.dwell_seconds < limit:
                continue
            zone = ctx.config.zone(det.zone)
            # workers standing around the warehouse at 2pm are normal; the perimeter is never a place to linger
            if ctx.config.is_business_hours(ctx.at) and not (zone and zone.perimeter):
                continue
            minutes = int(upd.dwell_seconds // 60)
            since = upd.entity.zone_since.strftime("%H:%M")
            yield self.alert(
                ctx, Severity.HIGH if ctx.is_night else Severity.MEDIUM,
                f"{det.display_name} loitering at {ctx.zone_name(det.zone)} for {minutes} min (since {since}), {ctx.hhmm}.",
                zone=det.zone, entity_id=det.entity_id,
                dedupe_key=f"{self.rule_id}|{det.entity_id}|{det.zone}|{since}",
                action="Escalate to security staff; person has not left the area.",
            )


class NightPresenceRule(Rule):
    """People on site at night: HIGH at the perimeter, MEDIUM anywhere else.

    Uniformed staff are skipped; in production this would be a badge / face whitelist.
    """

    rule_id = "R-NIGHT-PERSON"
    title = "Person on property during night hours"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        if not ctx.is_night:
            return
        for det, upd in ctx.observations:
            if det.category != "person" or "uniform" in det.attributes:
                continue
            zone = ctx.config.zone(det.zone)
            perimeter = bool(zone and zone.perimeter)
            yield self.alert(
                ctx, Severity.HIGH if perimeter else Severity.MEDIUM,
                f"{det.display_name} {_verb(det.action)} at {ctx.zone_name(det.zone)} during night hours, {ctx.hhmm}.",
                zone=det.zone, entity_id=det.entity_id,
                action="Verify identity on live feed; dispatch guard if not recognised.",
            )


class RestrictedZoneRule(Rule):
    rule_id = "R-RESTRICTED"
    title = "Person in restricted zone outside business hours"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        if ctx.config.is_business_hours(ctx.at):
            return
        for det, upd in ctx.observations:
            zone = ctx.config.zone(det.zone)
            if det.category == "person" and zone and zone.restricted:
                yield self.alert(
                    ctx, Severity.HIGH,
                    f"{det.display_name} in restricted area ({zone.name}) outside business hours, {ctx.hhmm}.",
                    zone=det.zone, entity_id=det.entity_id,
                    action="Check access-control logs for an authorised entry; otherwise dispatch guard.",
                )


class UnknownVehicleAfterHoursRule(Rule):
    rule_id = "R-VEHICLE-NIGHT"
    title = "Unrecognised vehicle on property at night"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        if not ctx.is_night:
            return
        for det, upd in ctx.observations:
            if det.category != "vehicle" or not upd.is_new_visit:
                continue
            if ctx.config.is_known_vehicle(det.color, det.make, det.model, det.label):
                continue
            yield self.alert(
                ctx, Severity.MEDIUM,
                f"Unrecognised {det.display_name} at {ctx.zone_name(det.zone)} after hours, {ctx.hhmm}.",
                zone=det.zone, entity_id=det.entity_id,
                action="Capture plate with zoom pass; confirm with property manager whether a visit was expected.",
            )


class RepeatVehicleRule(Rule):
    rule_id = "R-REPEAT-VEHICLE"
    title = "Same vehicle entering repeatedly in one day"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        threshold = ctx.config.thresholds.repeat_vehicle_visits
        for det, upd in ctx.observations:
            if det.category != "vehicle" or not upd.is_new_visit:
                continue
            if ctx.config.is_known_vehicle(det.color, det.make, det.model, det.label):
                continue
            visits = upd.entity.visits_on(ctx.at.date())
            if len(visits) < threshold:
                continue
            times = ", ".join(v.start.strftime("%H:%M") for v in visits)
            yield self.alert(
                ctx, Severity.LOW,
                f"{det.display_name} entered {_times(len(visits))} today ({times}), {ctx.hhmm}.",
                zone=det.zone, entity_id=det.entity_id,
                dedupe_key=f"{self.rule_id}|{det.entity_id}|{len(visits)}",
                action="Review whether repeat visits are expected (deliveries, contractors); add to whitelist if known.",
            )


class OpenAccessPointRule(Rule):
    rule_id = "R-ACCESS-OPEN"
    title = "Gate or door left open outside business hours"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        if ctx.config.is_business_hours(ctx.at):
            return
        for det, upd in ctx.observations:
            if det.category == "infrastructure" and "open" in det.attributes:
                yield self.alert(
                    ctx, Severity.MEDIUM,
                    f"{det.label.capitalize()} left open at {ctx.zone_name(det.zone)}, {ctx.hhmm}.",
                    zone=det.zone, dedupe_key=f"{self.rule_id}|{det.zone}|{det.label}",
                    action="Close remotely if motorised, otherwise send staff to secure it.",
                )


# --------------------------------------------------------------------- flight-safety rules
class BatteryRule(Rule):
    rule_id = "R-BATTERY"
    title = "Drone battery low"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        t = ctx.frame.telemetry
        th = ctx.config.thresholds
        if t.mode == "docked" or t.battery_pct > th.battery_low_pct:
            return
        critical = t.battery_pct <= th.battery_critical_pct
        yield self.alert(
            ctx, Severity.HIGH if critical else Severity.MEDIUM,
            f"Drone battery {'critical' if critical else 'low'} ({t.battery_pct:.0f}%) over {ctx.zone_name(t.zone)}, {ctx.hhmm}.",
            zone=t.zone, dedupe_key=f"{self.rule_id}|{'critical' if critical else 'low'}",
            action="Return to dock now." if critical else "Finish current waypoint, then return to dock to recharge.",
        )


class GeofenceRule(Rule):
    rule_id = "R-GEOFENCE"
    title = "Drone outside property geofence"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        t = ctx.frame.telemetry
        if t.distance_from_home_m > ctx.config.geofence_radius_m:
            yield self.alert(
                ctx, Severity.HIGH,
                f"Drone {t.distance_from_home_m:.0f} m from dock, outside {ctx.config.geofence_radius_m:.0f} m geofence, {ctx.hhmm}.",
                zone=t.zone, dedupe_key=self.rule_id,
                action="Trigger return-to-launch; check GPS health and wind drift.",
            )


class LowAltitudeRule(Rule):
    rule_id = "R-ALTITUDE"
    title = "Drone below minimum patrol altitude"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        t = ctx.frame.telemetry
        if t.mode == "patrol" and t.altitude_m < ctx.config.thresholds.min_patrol_altitude_m:
            yield self.alert(
                ctx, Severity.MEDIUM,
                f"Drone at {t.altitude_m:.0f} m over {ctx.zone_name(t.zone)}, below the {ctx.config.thresholds.min_patrol_altitude_m:.0f} m minimum, {ctx.hhmm}.",
                zone=t.zone, dedupe_key=self.rule_id,
                action="Climb to patrol altitude; check for obstacles and barometer drift.",
            )


class WindRule(Rule):
    rule_id = "R-WIND"
    title = "Wind above safe flight limit"

    def evaluate(self, ctx: RuleContext) -> Iterable[Alert]:
        t = ctx.frame.telemetry
        if t.mode != "docked" and t.wind_mps >= ctx.config.thresholds.max_wind_mps:
            yield self.alert(
                ctx, Severity.MEDIUM,
                f"High wind {t.wind_mps:.1f} m/s at {ctx.zone_name(t.zone)}, {ctx.hhmm}.",
                zone=t.zone, dedupe_key=self.rule_id,
                action="Shorten patrol loop and hold at dock until wind drops below limit.",
            )


def _times(n: int) -> str:
    return {1: "once", 2: "twice"}.get(n, f"{n} times")


def default_rules() -> list[Rule]:
    # ordered by specificity: when two rules fire for one entity at the same severity, the earlier one wins
    return [
        SuspiciousActivityRule(),
        LoiteringRule(),
        DwellTimeRule(),
        RestrictedZoneRule(),
        NightPresenceRule(),
        UnknownVehicleAfterHoursRule(),
        RepeatVehicleRule(),
        OpenAccessPointRule(),
        BatteryRule(),
        GeofenceRule(),
        LowAltitudeRule(),
        WindRule(),
    ]

